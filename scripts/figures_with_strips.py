#!/usr/bin/env python3
"""Main figures with a strip of atomic snapshots underneath that explains what is plotted.

Output: manuscript/figures/with_strips/<figure>_strip.{png,pdf}. The main panel is the existing
figure PNG; the strip is drawn from the MD structures (one (001) atomic plane, grey Fe, blue Cr).
"""
import sys
from pathlib import Path

import matplotlib.image as mpimg
import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from visualize_decomposition import CR, FE, read_data, series  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "manuscript" / "figures"
OUT = FIG / "with_strips"


from matplotlib.colors import ListedColormap  # noqa: E402

CMAP = ListedColormap([FE, CR])


def show_grid(ax, grid):
    ax.imshow(grid, cmap=CMAP, vmin=0, vmax=1, interpolation="nearest", origin="lower")
    ax.set_xticks([]); ax.set_yticks([])
    for sp in ax.spines.values():
        sp.set_linewidth(0.6)


def random_plane(ax, x, n=25, seed=7):
    """One (001) plane of a random bcc alloy (as generated by LAMMPS 'set type/fraction')."""
    show_grid(ax, (np.random.default_rng(seed).random((n, n)) < x).astype(int))


def md_plane(ax, path):
    """One (001) plane (z = 0 mod a) of an MD structure as a pixel grid."""
    t, p, box = read_data(path)
    L = box[:, 1] - box[:, 0]
    n = round(L[0] / 2.866); a = L[0] / n
    rel = (p - box[:, 0]) / a
    on = np.abs(rel[:, 2] - np.round(rel[:, 2])) < 0.1
    i, j = np.round(rel[on, 0]).astype(int) % n, np.round(rel[on, 1]).astype(int) % n
    grid = np.zeros((n, n), int); grid[j, i] = (t[on] == 2).astype(int)
    show_grid(ax, grid)


def compose(main_png, panels, strip_title, stem, note=None):
    """panels: list of (label, draw_function(ax))."""
    img = mpimg.imread(main_png)
    h, w = img.shape[:2]
    n = len(panels)
    fig_w = 7.2
    main_h = fig_w * h / w
    cell = fig_w / max(n, 6)
    fig = plt.figure(figsize=(fig_w, main_h + cell + 0.55))
    ncol = 2 * max(n, 6)
    gs = fig.add_gridspec(3, ncol, height_ratios=[main_h, 0.30, cell], hspace=0.04, wspace=0.16,
                          left=0.03, right=0.97, top=0.995, bottom=0.06 if note else 0.01)
    top = fig.add_subplot(gs[0, :]); top.imshow(img); top.axis("off")
    tt = fig.add_subplot(gs[1, :]); tt.axis("off")
    tt.text(0.5, 0.15, strip_title, ha="center", va="bottom", fontsize=7.5, fontweight="bold",
            transform=tt.transAxes)
    off = (ncol - 2 * n) // 2
    for k, (lab, fn) in enumerate(panels):
        ax = fig.add_subplot(gs[2, off + 2 * k: off + 2 * k + 2])
        fn(ax)
        ax.set_title(lab, fontsize=6.8, pad=1.5)
    if note:
        fig.text(0.5, 0.008, note, ha="center", va="bottom", fontsize=6.2, color="0.3")
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{stem}_strip.png", dpi=250, bbox_inches="tight")
    fig.savefig(OUT / f"{stem}_strip.pdf", bbox_inches="tight")
    plt.close(fig)


def snap(path):
    return lambda ax: md_plane(ax, path)


def main():
    plt.rcParams.update({"font.family": "DejaVu Sans"})
    ser = series()
    legend = "one atomic (001) plane of a 25$^3$ bcc MD cell: grey = Fe, blue = Cr"

    # Fig. 1: decomposed structures inside / outside the spinodal window
    xs = [x for x in (0.1, 0.2, 0.36, 0.5, 0.7, 0.95) if x in ser]
    panels = [(f"{round(100 * x)}% Cr", snap(ser[x][-1])) for x in xs]
    compose(FIG / "fig1_free_energy.png", panels,
            "Fully decomposed MD structures ($\\phi$ = 1): two phases form inside the spinodal window",
            "fig1_free_energy", legend)

    # Fig. 2 (both the current version and the orientation/bulk version): homogeneous random alloys
    xs2 = (0.0, 0.2, 0.36, 0.5, 0.8, 1.0)
    panels = [(f"{round(100 * x)}% Cr", (lambda x: (lambda ax: random_plane(ax, x)))(x)) for x in xs2]
    title2 = "Homogeneous (random) solid solutions: each tensor in the figure describes one of these"
    for stem in ("fig2_elastic_mapping", "fig2_elastic_mapping_orientation_violin_bulk"):
        if (FIG / f"{stem}.png").exists():
            compose(FIG / f"{stem}.png", panels, title2, stem, "one atomic (001) plane of a random bcc alloy: "
                    "grey = Fe, blue = Cr")

    # Fig. 3: Fe-36Cr partitioning (a) and the 50/50 conversion series (b)
    for stem, x, title in (("fig3_fsaw", 0.36, "Fe$_{64}$Cr$_{36}$ decomposing: Fe-rich $\\alpha$ (grey) and "
                                                "Cr-rich $\\alpha'$ (blue) regions form as $\\phi$ goes 0.5 $\\to$ 1"),
                           ("fig3_fsaw_relative", 0.36, None), ("fig3_fsaw_mddecomp", 0.36, None),
                           ("fig3_fsaw_alpha", 0.36, None)):
        if x not in ser or not (FIG / f"{stem}.png").exists():
            continue
        panels = [(rf"$\phi$ = {float(f.stem[3:]):.1f}", snap(f)) for f in ser[x]]
        compose(FIG / f"{stem}.png", panels, title or ("Fe$_{64}$Cr$_{36}$ decomposing: Fe-rich $\\alpha$ (grey) "
                "and Cr-rich $\\alpha'$ (blue) regions form as $\\phi$ goes 0.5 $\\to$ 1"), stem, legend)
    print(sorted(p.name for p in OUT.glob("*.png")))


if __name__ == "__main__":
    main()
